const DICTS = { en, fr, es, de, it, 'pt-BR': ptBR };

function strings(lang) {
  return { ...en, ...(DICTS[lang] || {}) };
}
function normalize(lang) {
  return DICTS[lang] ? lang : 'en';
}
function format(str, vars = {}) {
  return String(str).replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}
function translator(lang) {
  const dict = strings(normalize(lang));
  return (key, vars) => format(dict[key] ?? key, vars);
}

module.exports = { LANGUAGES, strings, normalize, translator };
